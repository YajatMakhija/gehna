import assert from 'node:assert/strict';
import { randomBytes } from 'node:crypto';
import { readFileSync } from 'node:fs';

const env = Object.fromEntries(readFileSync('storefront/.env.local', 'utf8').split(/\r?\n/).filter(Boolean).map(line => line.split(/=(.*)/s).slice(0, 2)));
const localConfig = readFileSync('backend/.env', 'utf8').replace(/\r/g, '');
if (/^AUTO_SHIP=true$/m.test(localConfig)) throw new Error('Disable real Shiprocket booking before local COD smoke testing.');
const email = `codex-cod-${randomBytes(5).toString('hex')}@example.test`;
const password = randomBytes(18).toString('base64url');
const phone = '9' + String(randomBytes(5).readUInt32BE(0) % 1_000_000_000).padStart(9, '0');
const base = 'http://localhost:9000';
async function request(path, method = 'GET', body, token) {
  const response = await fetch(base + path, { method, headers: { 'Content-Type': 'application/json', 'x-publishable-api-key': env.NEXT_PUBLIC_MEDUSA_PUBLISHABLE_KEY, ...(token ? { Authorization: 'Bearer ' + token } : {}) }, ...(body === undefined ? {} : { body: JSON.stringify(body) }) });
  const data = await response.json().catch(() => ({}));
  if (!response.ok) throw new Error(`${path} (${response.status}): ${JSON.stringify(data)}`);
  return data;
}
const qaAdmin = JSON.parse(readFileSync('.local/admin-credentials.json', 'utf8'));
const qaLogin = await request('/auth/user/emailpass', 'POST', qaAdmin);
const qaConfig = await request('/admin/gehna/overview', 'GET', undefined, qaLogin.token);
assert.equal(qaConfig.email_ready, false, 'Disable email in the running local backend before testing');
assert.equal(qaConfig.couriers.auto_enabled, false, 'Disable shipping in the running local backend before testing');
const registered = await request('/auth/customer/emailpass/register', 'POST', { email, password });
await request('/store/customers', 'POST', { email, first_name: 'COD', last_name: 'QA', phone }, registered.token);
const { token } = await request('/auth/customer/emailpass', 'POST', { email, password });
const { products } = await request(`/store/products?region_id=${env.NEXT_PUBLIC_MEDUSA_REGION_ID}&fields=id,title,*variants,variants.inventory_quantity&limit=10`);
const product = products.find(p => p.variants?.some(v => v.inventory_quantity > 0));
assert(product, 'Need an in-stock local test product');
const { cart } = await request('/store/carts', 'POST', { region_id: env.NEXT_PUBLIC_MEDUSA_REGION_ID }, token);
await request(`/store/carts/${cart.id}/customer`, 'POST', {}, token);
await request(`/store/carts/${cart.id}/line-items`, 'POST', { variant_id: product.variants[0].id, quantity: 1 }, token);
const address = { first_name: 'COD', last_name: 'QA', address_1: 'Local checkout test address', city: 'Delhi', province: 'Delhi', postal_code: '110001', country_code: 'in', phone };
await request(`/store/carts/${cart.id}`, 'POST', { email, shipping_address: address, billing_address: address }, token);
const { shipping_options } = await request(`/store/shipping-options?cart_id=${cart.id}`, 'GET', undefined, token);
assert(shipping_options.length, 'Need a shipping option');
await request(`/store/carts/${cart.id}/shipping-methods`, 'POST', { option_id: shipping_options[0].id }, token);
const { payment_providers } = await request(`/store/payment-providers?region_id=${env.NEXT_PUBLIC_MEDUSA_REGION_ID}`, 'GET', undefined, token);
assert.deepEqual(payment_providers.map(p => p.id), ['pp_system_default']);
const collection = await request('/store/payment-collections', 'POST', { cart_id: cart.id }, token);
await request(`/store/payment-collections/${collection.payment_collection.id}/payment-sessions`, 'POST', { provider_id: 'pp_system_default' }, token);
const completed = await request(`/store/carts/${cart.id}/complete`, 'POST', {}, token);
assert.equal(completed.type, 'order');
assert.equal(completed.order.email, email);
assert.equal(completed.order.currency_code, 'inr');
const owner = JSON.parse(readFileSync('.local/admin-credentials.json', 'utf8'));
const loginResponse = await fetch(base + '/auth/user/emailpass', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(owner) });
assert.equal(loginResponse.status, 200);
const { token: ownerToken } = await loginResponse.json();
const month = new Intl.DateTimeFormat('en-CA', { year: 'numeric', month: '2-digit', timeZone: 'Asia/Kolkata' }).format(new Date());
const overviewResponse = await fetch(`${base}/admin/gehna/overview?month=${month}`, { headers: { Authorization: `Bearer ${ownerToken}` } });
assert.equal(overviewResponse.status, 200);
const overview = await overviewResponse.json();
const row = overview.order_rows.find(o => o.id === completed.order.id);
assert(row, 'New order missing from owner dashboard');
assert.equal(row.cod, true, `COD order incorrectly classified: ${JSON.stringify({ payment_status: row.payment_status, payments: row.payments.map(p => p.provider), authorized: row.authorized, captured: row.captured })}`);
assert.equal(row.shipment.status, 'pending');
assert.equal(row.captured, 0);
console.log(`COD checkout passed. Local test order #${completed.order.display_id}; no real email or courier request.`);
const unconfirmed = await fetch(base + '/admin/gehna/assistant', { method: 'POST', headers: { Authorization: `Bearer ${ownerToken}`, 'Content-Type': 'application/json' }, body: JSON.stringify({ action: 'cancel', order_id: completed.order.id }) });
assert.equal(unconfirmed.status, 400, 'Assistant cancellation must require confirmation');
const canceled = await request('/admin/gehna/assistant', 'POST', { action: 'cancel', order_id: completed.order.id, confirm: true }, ownerToken);
assert.equal(canceled.order.status, 'canceled');
console.log('Assistant confirmed cancellation passed; order record preserved.');
